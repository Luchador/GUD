#!/usr/bin/env python3
"""Generate display names without using the enum to limit ROM enumeration."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[3]
source = (root / 'src/bondconstants.h').read_text()
body = re.search(r'typedef enum SFX_ID\s*\{(.*?)\}\s*SFX_ID;', source, re.S)[1]
body = re.sub(r'/\*.*?\*/|//[^\n]*', '', body, flags=re.S)
lines = ['/* Generated by scripts/generate_sfx_names.py; do not edit. */',
         'static const char *const g_SfxNames[] = {']
value = -1
for entry in body.split(','):
    entry = entry.strip()
    if not entry:
        continue
    match = re.fullmatch(r'(\w+)(?:\s*=\s*(0[xX][0-9a-fA-F]+|\d+))?', entry)
    if not match:
        raise ValueError(f'Unsupported SFX enum entry: {entry}')
    value = int(match[2], 0) if match[2] else value + 1
    name = match[1].removesuffix('_SFX').replace('_', ' ').capitalize()
    lines.append(f'    [{value}] = "{name}",')
lines += ['};', '']
output = root / 'tools/geditor/src/sfxnames.h'
text = '\n'.join(lines)
if not output.exists() or output.read_text() != text:
    output.write_text(text)
