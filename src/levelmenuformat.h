#ifndef GUD_LEVELMENUFORMAT_H
#define GUD_LEVELMENUFORMAT_H
#include "levelids.h"

#define LEVEL_MENU_VERSION 1u
#define LEVEL_MENU_KIND 0x4c56534cu /* LVSL */
#define LEVEL_MENU_SOLO_COUNT 20
#define LEVEL_MENU_MULTI_COUNT 12
#define LEVEL_MENU_SLOT_COUNT (LEVEL_MENU_SOLO_COUNT + LEVEL_MENU_MULTI_COUNT)
#define LEVEL_MENU_ROM_SIZE (4u + LEVEL_MENU_SLOT_COUNT * 4u)
/* Row-major menu order. MP variants are explicit catalog IDs, not row indices.
 * -1 is Random and is valid only in the multiplayer grid. */
#define LEVEL_MENU_DEFAULT_STAGES { \
    LEVELID_DAM, LEVELID_FACILITY, LEVELID_RUNWAY, LEVELID_SURFACE, LEVELID_BUNKER1, \
    LEVELID_SILO, LEVELID_FRIGATE, LEVELID_SURFACE2, LEVELID_BUNKER2, LEVELID_STATUE, \
    LEVELID_ARCHIVES, LEVELID_STREETS, LEVELID_DEPOT, LEVELID_TRAIN, LEVELID_JUNGLE, \
    LEVELID_CONTROL, LEVELID_CAVERNS, LEVELID_CRADLE, LEVELID_AZTEC, LEVELID_EGYPT, \
    LEVELID_NONE, LEVELID_TEMPLE, LEVELID_COMPLEX, LEVELID_CAVES, LEVELID_LIBRARY, \
    LEVELID_BASEMENT, LEVELID_STACK, LEVELID_FACILITY_MP, LEVELID_BUNKER2_MP, \
    LEVELID_ARCHIVES_MP, LEVELID_CAVERNS_MP, LEVELID_EGYPT_MP }
typedef struct LevelMenuConfig {
    unsigned int version;
    int stages[LEVEL_MENU_SLOT_COUNT];
} LevelMenuConfig;
typedef char LevelMenuConfigSizeCheck[sizeof(LevelMenuConfig) == LEVEL_MENU_ROM_SIZE ? 1 : -1];
#endif
